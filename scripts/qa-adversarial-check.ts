import { matchQA } from '../lib/qaMatch';
import type { QAEntry } from '../lib/types';

const mk = (
  id: string,
  question: string,
  aliases: string[] = []
): QAEntry => ({
  id,
  profileId: 'p',
  question,
  aliases,
  answer: `${question} 的答案`,
  tags: [],
  createdAt: 0,
  updatedAt: 0,
});

const all: QAEntry[] = [
  mk('1', '请先做一个自我介绍', ['自我介绍', '简单介绍一下自己', '介绍一下你自己']),
  mk('2', '为什么选择我们公司', ['为什么来我们公司', '为什么想加入']),
  mk('3', '为什么选择这个岗位', ['为什么想做这个岗位']),
  mk('4', '你最大的优点是什么', ['你最大的优势是什么', '你的强项是什么']),
  mk('5', '你最大的缺点是什么', ['你觉得自己有什么不足', '你的短板是什么']),
  mk('6', '你最大的成就是什么', ['你最有成就感的一件事是什么', '你最自豪的项目']),
  mk('7', '能不能接受工作岗位调剂', ['岗位调剂可以接受吗', '接受调岗吗']),
  mk('8', '能不能接受工作地点调剂', ['地点调剂可以接受吗', '接受城市调剂吗']),
  mk('9', '你期望的薪资是多少', ['期望薪资多少', '薪资要求']),
  mk('10', '你当前的薪资是多少', ['目前薪资多少', '现在工资多少']),
  mk('11', '你平时加班多吗', ['能接受加班吗', '加班情况怎么样']),
  mk('12', '你能接受出差吗', ['出差频率怎么样', '经常出差可以吗']),
  mk('13', '你了解我们公司吗', ['对我们公司了解多少', '知道我们做什么吗']),
  mk('14', '你的职业规划是什么', ['未来三到五年规划', '发展规划']),
  mk('15', '你为什么离职', ['为什么离开上一家', '辞职原因']),
  mk('16', '你做过最有挑战的项目是什么', ['项目里最难的部分']),
  mk('17', '你和同事发生冲突怎么处理', ['团队意见不一致怎么办']),
  mk('18', '你还有什么问题想问我们', ['反问环节', '你有什么想问的']),
  mk('19', '你怎么面对压力', ['抗压能力怎么样']),
  mk('20', '你最近在学什么', ['学习计划']),
];

const noUnderstanding = all.filter((x) => x.id !== '13');

const cases: [string, QAEntry[], string | null][] = [
  ['请你先做一个自我介绍', all, '1'],
  ['请做一个自我介绍', all, '1'],
  ['自我介绍', all, '1'],
  ['简单介绍一下自己', all, '1'],
  ['你最大的优势是什么', all, '4'],
  ['你觉得自己有什么不足', all, '5'],
  ['你期望薪资多少', all, '9'],
  ['为什么离职', all, '15'],
  ['你还有什么问题想问我们', all, '18'],
  ['你最大的缺点是什么', all, '5'],
  ['你最有成就感的一件事是什么', all, '6'],
  ['能不能接受工作岗位调剂', all, '7'],
  ['能不能接受工作地点调剂', all, '8'],
  ['当前薪资多少', all, '10'],
  ['你平时加班多吗', all, '11'],
  ['你能接受出差吗', all, '12'],
  ['你对我们公司了解多少', all, '13'],
  ['你对我们公司了解多少', noUnderstanding, null],
  ['你了解我们公司吗，为什么选择我们公司', all, null],
  ['岗位和地点都能调剂吗', all, null],
  ['你最大的优点是什么，缺点呢', all, null],
  ['你团队里有几个人', all, null],
];

let failed = 0;
for (const [q, list, want] of cases) {
  const hit = matchQA(q, list);
  const got = hit?.entry.id ?? null;
  if (got !== want) {
    failed++;
    console.log(`FAIL ${q}: got=${got}${hit ? ` score=${hit.score}` : ''} want=${want}`);
  } else {
    console.log(`ok   ${q} -> ${got}`);
  }
}
console.log(failed ? `\n${failed} FAILED` : '\nALL PASS');
process.exit(failed ? 1 : 0);
